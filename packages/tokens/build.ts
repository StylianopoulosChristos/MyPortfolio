// Builds src/*.json (W3C DTCG) into dist/: one CSS file per tier plus typed maps.
// Values pass through verbatim; only names are transformed (kebab-case).
import { readFileSync, writeFileSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';
import type { FormatFnArguments, TransformedToken } from 'style-dictionary/types';

type Block = { selector: string; media?: string };

const HEADER = '/* Generated by @cs/tokens — do not edit */';

const byName = (a: TransformedToken, b: TransformedToken) => a.name.localeCompare(b.name);

StyleDictionary.registerFormat({
  name: 'css/blocks',
  format: ({ dictionary, options }: FormatFnArguments) => {
    const blocks = options.blocks as Block[];
    const colorScheme = options.colorScheme as string | undefined;
    const declarations = [...dictionary.allTokens]
      .sort(byName)
      .map((token) => `--${token.name}: ${token.$value};`);
    if (colorScheme) declarations.unshift(`color-scheme: ${colorScheme};`);

    const rendered = blocks.map(({ selector, media }) => {
      const indent = media ? '    ' : '  ';
      const rule = `${selector} {\n${declarations.map((d) => indent + d).join('\n')}\n${media ? '  ' : ''}}`;
      return media ? `@media ${media} {\n  ${rule}\n}` : rule;
    });
    return `${HEADER}\n${rendered.join('\n\n')}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'ts/flat-map',
  format: ({ dictionary, options }: FormatFnArguments) => {
    const entries = [...dictionary.allTokens]
      .sort(byName)
      .map((token) => `  ${JSON.stringify(token.name)}: ${JSON.stringify(token.$value)},`);
    return `// Generated by @cs/tokens — do not edit\nexport const ${options.exportName} = {\n${entries.join('\n')}\n} as const;\n`;
  },
});

const isColor = (token: TransformedToken) => token.path[0] === 'color';

async function build(
  name: 'base' | 'dark' | 'light',
  source: string[],
  blocks: Block[],
  colorScheme?: 'dark' | 'light',
) {
  const filter = name === 'base' ? undefined : isColor;
  const sd = new StyleDictionary({
    source,
    usesDtcg: true,
    log: { verbosity: 'silent' },
    platforms: {
      tokens: {
        transforms: ['name/kebab'],
        buildPath: 'dist/',
        files: [
          {
            destination: `${name}.css`,
            format: 'css/blocks',
            filter,
            options: { blocks, colorScheme },
          },
          {
            destination: `${name}.ts`,
            format: 'ts/flat-map',
            filter,
            options: { exportName: name },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

await build('base', ['src/base.json'], [{ selector: ':root' }]);
await build(
  'dark',
  ['src/palette.json', 'src/semantic/dark.json'],
  [{ selector: ':root, :root[data-theme="dark"]' }],
  'dark',
);
await build(
  'light',
  ['src/palette.json', 'src/semantic/light.json'],
  [
    { selector: ':root[data-theme="light"]' },
    { selector: ':root:not([data-theme])', media: '(prefers-color-scheme: light)' },
  ],
  'light',
);

const combined = ['base', 'dark', 'light']
  .map((name) => readFileSync(`dist/${name}.css`, 'utf8'))
  .join('\n');
writeFileSync('dist/tokens.css', combined);
